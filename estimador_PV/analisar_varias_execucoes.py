#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Analyze the final results of multiple independent BtM-PV experiments.

IMPORTANT
---------
This script uses ONLY the FINAL estimation produced by the estimator:

    Resultados_finais_por_cenario_FP1.xlsx
    Resultados_finais_por_cenario_VV.xlsx

It does NOT use the individual cluster results to select the best cluster.

For each execution, scenario, condition and k, the row
"Potência estimada final (kW)" is treated as the result of the experiment.

Expected directory structure:

    <project_root>/
        experimentos/
            experimento_10_execucoes/
                execucao_01/
                execucao_02/
                ...
                execucao_10/

The script is intentionally independent of the OpenDSS simulations. It only
reads the Excel files already generated by the estimator.
"""

from pathlib import Path
import warnings

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# =============================================================================
# CONFIGURATION
# =============================================================================

NUM_EXECUCOES = 10

ESTIMADOR_DIR = Path(__file__).resolve().parent
ROOT = ESTIMADOR_DIR.parent

EXPERIMENTOS_DIR = (
    ROOT
    / "experimentos"
    / "experimento_10_execucoes"
)

OUTPUT_DIR = (
    ESTIMADOR_DIR
    / "analysis_results_multiplas_execucoes"
)

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


# Final files generated by main_estimar_PV_FP1_VoltVar.py
ARQUIVOS_FINAIS = {
    "FP1": "Resultados_finais_por_cenario_FP1.xlsx",
    "VV": "Resultados_finais_por_cenario_VV.xlsx",
}


# =============================================================================
# FILE DISCOVERY
# =============================================================================

def localizar_arquivo_final(pasta, tipo):
    """
    Locate the final result file for one inverter condition.

    The current estimator uses:
        Resultados_finais_por_cenario_FP1.xlsx
        Resultados_finais_por_cenario_VV.xlsx

    A fallback to the generic
        Resultados_finais_por_cenario.xlsx
    is allowed only when the parent/path clearly identifies the condition.
    """

    nome = ARQUIVOS_FINAIS[tipo]

    encontrados = list(pasta.rglob(nome))

    if encontrados:
        return encontrados[0]

    # Fallback for older executions.
    candidatos = list(
        pasta.rglob("Resultados_finais_por_cenario.xlsx")
    )

    if len(candidatos) == 1:
        caminho = candidatos[0]
        texto = str(caminho).lower()

        if tipo == "VV" and (
            "volt" in texto
            or "_vv" in texto
            or "vv" in texto
        ):
            return caminho

        if tipo == "FP1" and (
            "fp1" in texto
            or "sem_vv" in texto
            or "without" in texto
        ):
            return caminho

    return None


# =============================================================================
# LOAD FINAL RESULTS
# =============================================================================

def carregar_resultado_final(arquivo, tipo, execucao):
    """Read and validate one final-result Excel file."""

    df = pd.read_excel(arquivo)

    colunas_obrigatorias = {
        "k",
        "Cenário",
        "Potência Real (kW)",
        "Potência estimada final (kW)",
        "Erro (%)",
    }

    faltantes = colunas_obrigatorias - set(df.columns)

    if faltantes:
        raise ValueError(
            f"Missing columns in {arquivo.name}: {sorted(faltantes)}"
        )

    df = df.copy()

    df["Condition"] = tipo
    df["Execution"] = execucao
    df["Source File"] = str(arquivo)

    return df


# =============================================================================
# DISCOVER AND LOAD ALL EXECUTIONS
# =============================================================================

def carregar_todas_execucoes():
    resultados = []
    status = []

    if not EXPERIMENTOS_DIR.exists():
        raise FileNotFoundError(
            "Experiment directory not found:\n"
            f"{EXPERIMENTOS_DIR}"
        )

    for numero in range(1, NUM_EXECUCOES + 1):

        pasta = (
            EXPERIMENTOS_DIR
            / f"execucao_{numero:02d}"
        )

        registro = {
            "Execution": numero,
            "Folder": str(pasta),
            "FP1": False,
            "Volt-VAr": False,
            "FP1_File": "",
            "Volt-VAr_File": "",
            "Error": "",
        }

        if not pasta.exists():
            registro["Error"] = "Execution folder not found."
            status.append(registro)
            continue

        for tipo in ("FP1", "VV"):

            try:
                arquivo = localizar_arquivo_final(
                    pasta,
                    tipo
                )

                if arquivo is None:
                    continue

                df = carregar_resultado_final(
                    arquivo,
                    tipo,
                    numero
                )

                resultados.append(df)

                if tipo == "FP1":
                    registro["FP1"] = True
                    registro["FP1_File"] = str(arquivo)
                else:
                    registro["Volt-VAr"] = True
                    registro["Volt-VAr_File"] = str(arquivo)

            except Exception as exc:
                registro["Error"] += (
                    f"{tipo}: {exc}; "
                )

        status.append(registro)

    if not resultados:
        raise RuntimeError(
            "No final-result files were found."
        )

    dados = pd.concat(
        resultados,
        ignore_index=True
    )

    return dados, pd.DataFrame(status)


# =============================================================================
# VALIDATION
# =============================================================================

def validar_dados(df):
    """Check for duplicate experiment results."""

    chave = [
        "Execution",
        "Condition",
        "Cenário",
        "k",
    ]

    duplicados = (
        df.groupby(chave)
        .size()
        .reset_index(name="Count")
    )

    duplicados = duplicados[
        duplicados["Count"] > 1
    ]

    if not duplicados.empty:
        raise ValueError(
            "Duplicate final results found for the same "
            "execution/condition/scenario/k:\n\n"
            f"{duplicados.to_string(index=False)}"
        )

    df["Absolute Error (%)"] = df["Erro (%)"].abs()

    return df


# =============================================================================
# STATISTICAL SUMMARY
# =============================================================================

def calcular_resumo(df):
    """
    Statistics are calculated from the FINAL result of each execution.

    No cluster selection is performed.
    """

    resumo = (
        df.groupby(
            ["Condition", "Cenário", "k"],
            as_index=False
        )
        .agg(
            Executions=(
                "Execution",
                "nunique"
            ),

            Mean_Error=(
                "Erro (%)",
                "mean"
            ),

            Min_Error=(
                "Erro (%)",
                "min"
            ),

            Max_Error=(
                "Erro (%)",
                "max"
            ),

            Mean_Absolute_Error=(
                "Absolute Error (%)",
                "mean"
            ),

            Std_Error=(
                "Erro (%)",
                "std"
            ),

            Mean_Estimated_Power=(
                "Potência estimada final (kW)",
                "mean"
            ),

            Mean_Actual_Power=(
                "Potência Real (kW)",
                "mean"
            ),
        )
        .sort_values(
            ["Condition", "k", "Cenário"]
        )
        .reset_index(drop=True)
    )

    return resumo


# =============================================================================
# SIMPLIFIED TABLE FOR THE ARTICLE
# =============================================================================

def tabela_artigo(df):
    """
    Compact table:
        PV penetration
        k
        mean error
        minimum error
        maximum error

    Generated separately for FP=1 and Volt-VAr.
    """

    tabela = (
        df.groupby(
            ["Condition", "Cenário", "k"],
            as_index=False
        )
        .agg(
            Mean_Error=(
                "Erro (%)",
                "mean"
            ),
            Min_Error=(
                "Erro (%)",
                "min"
            ),
            Max_Error=(
                "Erro (%)",
                "max"
            ),
        )
        .sort_values(
            ["Condition", "k", "Cenário"]
        )
    )

    return tabela


# =============================================================================
# PAIRED COMPARISON: FP1 vs VOLT-VAR
# =============================================================================

def comparar_condicoes(df):
    """
    Compare the two inverter conditions using the same execution,
    scenario and k.

    This is a paired comparison because the same stochastic PV
    realization is supposed to be simulated under both conditions.
    """

    colunas = [
        "Execution",
        "Cenário",
        "k",
        "Erro (%)",
        "Potência estimada final (kW)",
    ]

    fp1 = (
        df[df["Condition"] == "FP1"][colunas]
        .rename(
            columns={
                "Erro (%)": "Error_FP1",
                "Potência estimada final (kW)":
                    "Estimated_Power_FP1",
            }
        )
    )

    vv = (
        df[df["Condition"] == "VV"][colunas]
        .rename(
            columns={
                "Erro (%)": "Error_VoltVar",
                "Potência estimada final (kW)":
                    "Estimated_Power_VoltVar",
            }
        )
    )

    comparacao = pd.merge(
        fp1,
        vv,
        on=["Execution", "Cenário", "k"],
        how="outer",
        validate="one_to_one",
    )

    comparacao["Error_Difference_pp"] = (
        comparacao["Error_VoltVar"]
        - comparacao["Error_FP1"]
    )

    comparacao["Estimated_Power_Difference_kW"] = (
        comparacao["Estimated_Power_VoltVar"]
        - comparacao["Estimated_Power_FP1"]
    )

    return comparacao


def resumo_comparacao(comparacao):
    """Aggregate the paired FP1 vs Volt-VAr comparison."""

    disponiveis = comparacao.dropna(
        subset=["Error_FP1", "Error_VoltVar"]
    )

    if disponiveis.empty:
        return pd.DataFrame()

    resumo = (
        disponiveis.groupby(
            ["Cenário", "k"],
            as_index=False
        )
        .agg(
            Paired_Executions=(
                "Execution",
                "nunique"
            ),
            Mean_Error_FP1=(
                "Error_FP1",
                "mean"
            ),
            Mean_Error_VoltVar=(
                "Error_VoltVar",
                "mean"
            ),
            Mean_Error_Difference_pp=(
                "Error_Difference_pp",
                "mean"
            ),
            Min_Error_Difference_pp=(
                "Error_Difference_pp",
                "min"
            ),
            Max_Error_Difference_pp=(
                "Error_Difference_pp",
                "max"
            ),
        )
        .sort_values(
            ["k", "Cenário"]
        )
    )

    return resumo


# =============================================================================
# OVERALL SUMMARY
# =============================================================================

def resumo_geral(df):
    """Overall statistics by inverter condition and k."""

    return (
        df.groupby(
            ["Condition", "k"],
            as_index=False
        )
        .agg(
            Executions=(
                "Execution",
                "nunique"
            ),
            Mean_Error=(
                "Erro (%)",
                "mean"
            ),
            Min_Error=(
                "Erro (%)",
                "min"
            ),
            Max_Error=(
                "Erro (%)",
                "max"
            ),
            Std_Error=(
                "Erro (%)",
                "std"
            ),
        )
        .sort_values(
            ["Condition", "k"]
        )
    )


# =============================================================================
# PLOTS
# =============================================================================

def plot_error_distribution(df):
    """
    Boxplots of FINAL estimation error.

    If several k values exist, each k is shown separately.
    """

    for k in sorted(df["k"].dropna().unique()):

        dados_k = df[df["k"] == k].copy()

        if dados_k.empty:
            continue

        condicoes = ["FP1", "VV"]

        fig, ax = plt.subplots(
            figsize=(9, 5)
        )

        grupos = sorted(
            dados_k["Cenário"].dropna().unique()
        )

        posicoes = np.arange(len(grupos))

        for i, condicao in enumerate(condicoes):

            dados = dados_k[
                dados_k["Condition"] == condicao
            ]

            if dados.empty:
                continue

            valores = [
                dados[
                    dados["Cenário"] == c
                ]["Erro (%)"].dropna().values
                for c in grupos
            ]

            offset = (
                -0.18
                if condicao == "FP1"
                else 0.18
            )

            ax.boxplot(
                valores,
                positions=posicoes + offset,
                widths=0.30,
                labels=[
                    f"{int(c)}%"
                    for c in grupos
                ],
            )

        ax.set_xlabel("PV Penetration")
        ax.set_ylabel("Estimation Error (%)")

        ax.set_title(
            f"Final Estimation Error Across Independent Executions "
            f"(k = {k:.2f})"
        )

        ax.grid(
            True,
            axis="y"
        )

        fig.tight_layout()

        nome = (
            f"Error_Distribution_Final_k_{k:.2f}.png"
            .replace(".", "_", 1)
        )

        fig.savefig(
            OUTPUT_DIR / nome,
            dpi=300,
            bbox_inches="tight"
        )

        plt.close(fig)


def plot_mean_error(df):
    """Mean final error with standard deviation."""

    for k in sorted(df["k"].dropna().unique()):

        dados_k = df[df["k"] == k]

        fig, ax = plt.subplots(
            figsize=(8, 5)
        )

        for condicao in ("FP1", "VV"):

            dados = (
                dados_k[
                    dados_k["Condition"] == condicao
                ]
                .groupby("Cenário")
                .agg(
                    Mean=(
                        "Erro (%)",
                        "mean"
                    ),
                    Std=(
                        "Erro (%)",
                        "std"
                    ),
                )
                .reset_index()
                .sort_values("Cenário")
            )

            if dados.empty:
                continue

            ax.errorbar(
                dados["Cenário"],
                dados["Mean"],
                yerr=dados["Std"],
                marker="o",
                linewidth=2,
                capsize=4,
                label=(
                    "With Volt-VAr"
                    if condicao == "VV"
                    else "FP = 1"
                ),
            )

        ax.set_xlabel("PV Penetration (%)")
        ax.set_ylabel("Mean Estimation Error (%)")

        ax.set_title(
            f"Mean Final Estimation Error "
            f"(k = {k:.2f})"
        )

        ax.grid(True)
        ax.legend()

        fig.tight_layout()

        fig.savefig(
            OUTPUT_DIR
            / f"Mean_Error_k_{k:.2f}.png",
            dpi=300,
            bbox_inches="tight",
        )

        plt.close(fig)


def plot_estimated_capacity(df):
    """Mean final estimated capacity versus actual capacity."""

    for k in sorted(df["k"].dropna().unique()):

        dados_k = df[df["k"] == k]

        fig, ax = plt.subplots(
            figsize=(8, 5)
        )

        for condicao in ("FP1", "VV"):

            dados = (
                dados_k[
                    dados_k["Condition"] == condicao
                ]
                .groupby("Cenário")
                .agg(
                    Mean_Estimated=(
                        "Potência estimada final (kW)",
                        "mean"
                    ),
                    Std_Estimated=(
                        "Potência estimada final (kW)",
                        "std"
                    ),
                    Actual=(
                        "Potência Real (kW)",
                        "mean"
                    ),
                )
                .reset_index()
                .sort_values("Cenário")
            )

            if dados.empty:
                continue

            ax.errorbar(
                dados["Cenário"],
                dados["Mean_Estimated"],
                yerr=dados["Std_Estimated"],
                marker="o",
                linewidth=2,
                capsize=4,
                label=(
                    "With Volt-VAr"
                    if condicao == "VV"
                    else "FP = 1"
                ),
            )

        actual = (
            dados_k
            .groupby("Cenário")["Potência Real (kW)"]
            .mean()
            .reset_index()
            .sort_values("Cenário")
        )

        ax.plot(
            actual["Cenário"],
            actual["Potência Real (kW)"],
            marker="o",
            linestyle="--",
            linewidth=2,
            label="Actual PV Capacity",
        )

        ax.set_xlabel("PV Penetration (%)")
        ax.set_ylabel("PV Capacity (kW)")

        ax.set_title(
            f"Final Estimated PV Capacity "
            f"(k = {k:.2f})"
        )

        ax.grid(True)
        ax.legend()

        fig.tight_layout()

        fig.savefig(
            OUTPUT_DIR
            / f"Estimated_PV_Capacity_k_{k:.2f}.png",
            dpi=300,
            bbox_inches="tight",
        )

        plt.close(fig)


def plot_k_sensitivity(df):
    """
    If more than one k is available, show mean error versus k.
    This does NOT choose a best k automatically.
    """

    ks = sorted(
        df["k"].dropna().unique()
    )

    if len(ks) <= 1:
        return

    resumo = (
        df.groupby(
            ["Condition", "k"],
            as_index=False
        )["Erro (%)"]
        .mean()
    )

    fig, ax = plt.subplots(
        figsize=(8, 5)
    )

    for condicao in ("FP1", "VV"):

        dados = resumo[
            resumo["Condition"] == condicao
        ].sort_values("k")

        if dados.empty:
            continue

        ax.plot(
            dados["k"],
            dados["Erro (%)"],
            marker="o",
            linewidth=2,
            label=(
                "With Volt-VAr"
                if condicao == "VV"
                else "FP = 1"
            ),
        )

    ax.set_xlabel("k")
    ax.set_ylabel("Mean Estimation Error (%)")

    ax.set_title(
        "Mean Final Estimation Error as a Function of k"
    )

    ax.grid(True)
    ax.legend()

    fig.tight_layout()

    fig.savefig(
        OUTPUT_DIR
        / "K_Sensitivity_Mean_Error.png",
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(fig)


# =============================================================================
# MAIN
# =============================================================================

def main():

    print("=" * 90)
    print("MULTIPLE-EXECUTION FINAL RESULT ANALYSIS")
    print("=" * 90)

    print("\nExperiment directory:")
    print(EXPERIMENTOS_DIR)

    dados, status = carregar_todas_execucoes()

    dados = validar_dados(dados)

    print(
        f"\nFinal-result rows loaded: {len(dados)}"
    )

    print(
        "Executions found:",
        sorted(dados["Execution"].unique())
    )

    print(
        "Conditions:",
        sorted(dados["Condition"].unique())
    )

    print(
        "PV penetration levels:",
        sorted(dados["Cenário"].unique())
    )

    print(
        "k values:",
        sorted(dados["k"].unique())
    )

    # -------------------------------------------------------------------------
    # Statistics

    resumo = calcular_resumo(dados)

    artigo = tabela_artigo(dados)

    comparacao = comparar_condicoes(dados)

    comparacao_resumo = resumo_comparacao(
        comparacao
    )

    geral = resumo_geral(dados)

    # -------------------------------------------------------------------------
    # Save Excel

    excel_file = (
        OUTPUT_DIR
        / "Multiple_Executions_Final_Analysis.xlsx"
    )

    with pd.ExcelWriter(
        excel_file,
        engine="openpyxl"
    ) as writer:

        dados.to_excel(
            writer,
            sheet_name="Final_Results",
            index=False,
        )

        resumo.to_excel(
            writer,
            sheet_name="Statistical_Summary",
            index=False,
        )

        artigo.to_excel(
            writer,
            sheet_name="Article_Table",
            index=False,
        )

        comparacao.to_excel(
            writer,
            sheet_name="Paired_Comparison",
            index=False,
        )

        comparacao_resumo.to_excel(
            writer,
            sheet_name="Comparison_Summary",
            index=False,
        )

        geral.to_excel(
            writer,
            sheet_name="Overall_Summary",
            index=False,
        )

        status.to_excel(
            writer,
            sheet_name="Execution_Status",
            index=False,
        )

    # -------------------------------------------------------------------------
    # CSV files

    resumo.to_csv(
        OUTPUT_DIR
        / "Statistical_Summary.csv",
        index=False,
    )

    artigo.to_csv(
        OUTPUT_DIR
        / "Article_Table.csv",
        index=False,
    )

    comparacao_resumo.to_csv(
        OUTPUT_DIR
        / "Comparison_Summary.csv",
        index=False,
    )

    # -------------------------------------------------------------------------
    # Figures

    plot_error_distribution(dados)
    plot_mean_error(dados)
    plot_estimated_capacity(dados)
    plot_k_sensitivity(dados)

    # -------------------------------------------------------------------------
    # Console summary

    print("\n" + "=" * 90)
    print("ARTICLE TABLE")
    print("=" * 90)
    print(
        artigo.to_string(index=False)
    )

    print("\n" + "=" * 90)
    print("CONDITION COMPARISON")
    print("=" * 90)

    if comparacao_resumo.empty:
        print(
            "No paired FP1/Volt-VAr results available."
        )
    else:
        print(
            comparacao_resumo.to_string(
                index=False
            )
        )

    print("\n" + "=" * 90)
    print("ANALYSIS COMPLETED")
    print("=" * 90)

    print(
        f"\nResults saved to:\n{OUTPUT_DIR}"
    )


if __name__ == "__main__":
    main()
