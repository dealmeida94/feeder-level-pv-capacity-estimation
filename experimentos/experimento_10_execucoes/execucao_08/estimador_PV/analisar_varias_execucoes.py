#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Analyze multiple independent experiments of the BtM-PV-estimating project.

Expected location:
    <project_root>/estimador_PV/analisar_varias_execucoes.py

Expected experiment structure:
    <project_root>/experimentos/experimento_10_execucoes/
        execucao_01/
        execucao_02/
        ...
        execucao_10/

Each execution should contain the outputs generated by the complete pipeline.

The script searches each execution for the final estimation files and
compares the repeated experiments statistically.

IMPORTANT:
- It does NOT modify any experiment result.
- All analysis outputs are written to:
      estimador_PV/analysis_results_multiplas_execucoes/
- The analysis is in English.
"""

from pathlib import Path
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt


# ==========================================================
# PATHS
# ==========================================================

ESTIMADOR_DIR = Path(__file__).resolve().parent
ROOT = ESTIMADOR_DIR.parent

EXPERIMENTOS_DIR = (
    ROOT / "experimentos" / "experimento_10_execucoes"
)

OUTPUT_DIR = ESTIMADOR_DIR / "analysis_results_multiplas_execucoes"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

NUM_EXECUCOES = 10


# ==========================================================
# POSSIBLE RESULT FILE NAMES
# ==========================================================

RESULTADO_SEM_VV = [
    "Resultados_da_estimacao_por_clusters.xlsx",
    "Resultados_da_estimacao_por_clusters_FP1.xlsx",
    "Best_Estimation_Results.xlsx",
]

RESULTADO_COM_VV = [
    "Resultados_da_estimacao_por_clusters_VV.xlsx",
    "Resultados_da_estimacao_por_clusters_FP1_VV.xlsx",
]


# ==========================================================
# HELPERS
# ==========================================================

def localizar_arquivo(pasta, candidatos):
    """Search recursively for one of the candidate filenames."""

    for nome in candidatos:
        encontrados = list(pasta.rglob(nome))
        if encontrados:
            return encontrados[0]

    return None


def carregar_resultado(arquivo, condicao, execucao):
    """Read one estimation result file."""

    df = pd.read_excel(arquivo)

    obrigatorias = {
        "Cenário",
        "Cluster",
        "k",
        "Potência Real (kW)",
        "Potência estimada (kW)",
        "Erro (%)",
        "Acerto (%)",
    }

    faltantes = obrigatorias - set(df.columns)

    if faltantes:
        raise ValueError(
            f"Missing columns in {arquivo}: {sorted(faltantes)}"
        )

    df["Condition"] = condicao
    df["Execution"] = execucao

    return df


def selecionar_melhores(df):
    """
    Select the minimum-error result for each PV penetration
    within one execution and condition.
    """

    return (
        df.sort_values("Erro (%)")
        .groupby("Cenário", as_index=False)
        .first()
    )


# ==========================================================
# DISCOVER EXECUTIONS
# ==========================================================

print("=" * 100)
print("MULTIPLE-EXECUTION PV ESTIMATION ANALYSIS")
print("=" * 100)

if not EXPERIMENTOS_DIR.exists():
    raise FileNotFoundError(
        f"Experiment directory not found:\n{EXPERIMENTOS_DIR}"
    )

pastas_execucao = []

for numero in range(1, NUM_EXECUCOES + 1):
    pasta = EXPERIMENTOS_DIR / f"execucao_{numero:02d}"

    if pasta.exists():
        pastas_execucao.append((numero, pasta))

print(f"\nExperiment directory:")
print(f"  {EXPERIMENTOS_DIR}")

print(f"\nExecutions found: {len(pastas_execucao)}/{NUM_EXECUCOES}")


# ==========================================================
# LOAD ALL RESULTS
# ==========================================================

todos_resultados = []
status_execucoes = []

for numero, pasta in pastas_execucao:

    print(f"\nExecution {numero:02d}")

    sem_vv = localizar_arquivo(pasta, RESULTADO_SEM_VV)
    com_vv = localizar_arquivo(pasta, RESULTADO_COM_VV)

    if sem_vv:
        print(f"  Without Volt-VAr: {sem_vv}")
    else:
        print("  Without Volt-VAr: NOT FOUND")

    if com_vv:
        print(f"  With Volt-VAr:    {com_vv}")
    else:
        print("  With Volt-VAr:    NOT FOUND")

    sucesso_sem = False
    sucesso_com = False

    if sem_vv:
        try:
            todos_resultados.append(
                carregar_resultado(
                    sem_vv,
                    "Without Volt-VAr",
                    numero,
                )
            )
            sucesso_sem = True
        except Exception as erro:
            print(f"  ERROR reading without Volt-VAr: {erro}")

    if com_vv:
        try:
            todos_resultados.append(
                carregar_resultado(
                    com_vv,
                    "With Volt-VAr",
                    numero,
                )
            )
            sucesso_com = True
        except Exception as erro:
            print(f"  ERROR reading with Volt-VAr: {erro}")

    status_execucoes.append({
        "Execution": numero,
        "Without Volt-VAr": "OK" if sucesso_sem else "MISSING/ERROR",
        "With Volt-VAr": "OK" if sucesso_com else "MISSING/ERROR",
    })


if not todos_resultados:
    raise RuntimeError(
        "No valid estimation result files were found."
    )


resultados = pd.concat(todos_resultados, ignore_index=True)


# ==========================================================
# BEST RESULT PER EXECUTION / CONDITION / SCENARIO
# ==========================================================

melhores_execucoes = (
    resultados
    .sort_values("Erro (%)")
    .groupby(
        ["Execution", "Condition", "Cenário"],
        as_index=False
    )
    .first()
)


# ==========================================================
# STATISTICAL SUMMARY
# ==========================================================

agrupamento = (
    melhores_execucoes
    .groupby(["Condition", "Cenário"])
)

resumo = agrupamento.agg(
    Executions=("Execution", "count"),
    Mean_Error=("Erro (%)", "mean"),
    Std_Error=("Erro (%)", "std"),
    Min_Error=("Erro (%)", "min"),
    Max_Error=("Erro (%)", "max"),
    Median_Error=("Erro (%)", "median"),
    Mean_Accuracy=("Acerto (%)", "mean"),
    Std_Accuracy=("Acerto (%)", "std"),
    Mean_Estimated_Power=("Potência estimada (kW)", "mean"),
    Std_Estimated_Power=("Potência estimada (kW)", "std"),
    Mean_Actual_Power=("Potência Real (kW)", "mean"),
    Mean_RMSE=("RMSE", "mean") if "RMSE" in melhores_execucoes else
        ("Erro (%)", "mean"),
    Mean_MAE=("MAE", "mean") if "MAE" in melhores_execucoes else
        ("Erro (%)", "mean"),
).reset_index()


# ==========================================================
# BEST CLUSTER FREQUENCY
# ==========================================================

cluster_frequency = (
    melhores_execucoes
    .groupby(
        ["Condition", "Cenário", "Cluster"],
        as_index=False
    )
    .size()
    .rename(columns={"size": "Number of Executions"})
)

cluster_frequency["Frequency (%)"] = (
    cluster_frequency["Number of Executions"]
    / cluster_frequency.groupby(
        ["Condition", "Cenário"]
    )["Number of Executions"].transform("sum")
    * 100
)


# ==========================================================
# K STATISTICS
# ==========================================================

k_summary = (
    melhores_execucoes
    .groupby(["Condition", "Cenário"])
    .agg(
        Mean_k=("k", "mean"),
        Std_k=("k", "std"),
        Min_k=("k", "min"),
        Max_k=("k", "max"),
    )
    .reset_index()
)


# ==========================================================
# VOLT-VAR VS. WITHOUT VOLT-VAR
# ==========================================================

sem = melhores_execucoes[
    melhores_execucoes["Condition"] == "Without Volt-VAr"
].copy()

com = melhores_execucoes[
    melhores_execucoes["Condition"] == "With Volt-VAr"
].copy()

comparacao = sem.merge(
    com,
    on=["Execution", "Cenário"],
    suffixes=(" - Without Volt-VAr", " - With Volt-VAr")
)

comparacao["Error Difference (p.p.)"] = (
    comparacao["Erro (%) - With Volt-VAr"]
    - comparacao["Erro (%) - Without Volt-VAr"]
)

comparacao["Accuracy Difference (p.p.)"] = (
    comparacao["Acerto (%) - With Volt-VAr"]
    - comparacao["Acerto (%) - Without Volt-VAr"]
)

comparacao["Estimated Power Difference (kW)"] = (
    comparacao["Potência estimada (kW) - With Volt-VAr"]
    - comparacao["Potência estimada (kW) - Without Volt-VAr"]
)


# ==========================================================
# AGGREGATED VOLT-VAR COMPARISON
# ==========================================================

comparacao_resumo = (
    comparacao
    .groupby("Cenário")
    .agg(
        Executions=("Execution", "count"),
        Mean_Error_Without_VoltVar=(
            "Erro (%) - Without Volt-VAr", "mean"
        ),
        Mean_Error_With_VoltVar=(
            "Erro (%) - With Volt-VAr", "mean"
        ),
        Mean_Error_Difference=(
            "Error Difference (p.p.)", "mean"
        ),
        Std_Error_Difference=(
            "Error Difference (p.p.)", "std"
        ),
        Mean_Accuracy_Without_VoltVar=(
            "Acerto (%) - Without Volt-VAr", "mean"
        ),
        Mean_Accuracy_With_VoltVar=(
            "Acerto (%) - With Volt-VAr", "mean"
        ),
    )
    .reset_index()
)


# ==========================================================
# OVERALL SUMMARY
# ==========================================================

overall = (
    melhores_execucoes
    .groupby("Condition")
    .agg(
        Executions=("Execution", "nunique"),
        Mean_Error=("Erro (%)", "mean"),
        Std_Error=("Erro (%)", "std"),
        Mean_Accuracy=("Acerto (%)", "mean"),
        Std_Accuracy=("Acerto (%)", "std"),
    )
    .reset_index()
)


# ==========================================================
# SAVE EXCEL
# ==========================================================

excel_file = OUTPUT_DIR / "Multiple_Executions_Analysis.xlsx"

with pd.ExcelWriter(excel_file, engine="openpyxl") as writer:

    resumo.to_excel(
        writer,
        sheet_name="Statistical_Summary",
        index=False,
    )

    comparacao_resumo.to_excel(
        writer,
        sheet_name="VoltVar_Comparison",
        index=False,
    )

    comparacao.to_excel(
        writer,
        sheet_name="Paired_Executions",
        index=False,
    )

    melhores_execucoes.to_excel(
        writer,
        sheet_name="Best_Per_Execution",
        index=False,
    )

    cluster_frequency.to_excel(
        writer,
        sheet_name="Cluster_Frequency",
        index=False,
    )

    k_summary.to_excel(
        writer,
        sheet_name="K_Summary",
        index=False,
    )

    overall.to_excel(
        writer,
        sheet_name="Overall_Summary",
        index=False,
    )

    pd.DataFrame(status_execucoes).to_excel(
        writer,
        sheet_name="Execution_Status",
        index=False,
    )


# ==========================================================
# SAVE CSV FILES
# ==========================================================

resumo.to_csv(
    OUTPUT_DIR / "Statistical_Summary.csv",
    index=False,
)

comparacao_resumo.to_csv(
    OUTPUT_DIR / "VoltVar_Comparison.csv",
    index=False,
)

melhores_execucoes.to_csv(
    OUTPUT_DIR / "Best_Per_Execution.csv",
    index=False,
)

cluster_frequency.to_csv(
    OUTPUT_DIR / "Cluster_Frequency.csv",
    index=False,
)


# ==========================================================
# FIGURE 1 — ERROR DISTRIBUTION
# ==========================================================

plt.figure(figsize=(9, 5))

for condition in melhores_execucoes["Condition"].unique():

    dados = melhores_execucoes[
        melhores_execucoes["Condition"] == condition
    ]

    grupos = sorted(dados["Cenário"].unique())

    valores = [
        dados[dados["Cenário"] == c]["Erro (%)"].values
        for c in grupos
    ]

    positions = np.arange(len(grupos))

    # Small offset keeps the two conditions visually separated.
    offset = (
        -0.18 if condition == "Without Volt-VAr" else 0.18
    )

    plt.boxplot(
        valores,
        positions=positions + offset,
        widths=0.30,
        labels=[f"{int(c)}%" for c in grupos],
    )

plt.xlabel("PV Penetration")
plt.ylabel("Estimation Error (%)")
plt.title("Estimation Error Across Independent Executions")
plt.grid(True, axis="y")
plt.tight_layout()
plt.savefig(
    OUTPUT_DIR / "Error_Distribution_All_Executions.png",
    bbox_inches="tight",
)
plt.close()


# ==========================================================
# FIGURE 2 — MEAN ERROR
# ==========================================================

plt.figure(figsize=(8, 5))

for condition in resumo["Condition"].unique():

    dados = resumo[
        resumo["Condition"] == condition
    ].sort_values("Cenário")

    plt.errorbar(
        dados["Cenário"],
        dados["Mean_Error"],
        yerr=dados["Std_Error"],
        marker="o",
        linewidth=2,
        capsize=4,
        label=condition,
    )

plt.xlabel("PV Penetration (%)")
plt.ylabel("Mean Estimation Error (%)")
plt.title("Mean Estimation Error Across Executions")
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.savefig(
    OUTPUT_DIR / "Mean_Error_With_Standard_Deviation.png",
    bbox_inches="tight",
)
plt.close()


# ==========================================================
# FIGURE 3 — ESTIMATED CAPACITY
# ==========================================================

plt.figure(figsize=(8, 5))

for condition in resumo["Condition"].unique():

    dados = resumo[
        resumo["Condition"] == condition
    ].sort_values("Cenário")

    plt.errorbar(
        dados["Cenário"],
        dados["Mean_Estimated_Power"],
        yerr=dados["Std_Estimated_Power"],
        marker="o",
        linewidth=2,
        capsize=4,
        label=condition,
    )

# Actual capacity is common to the two conditions.
actual = (
    resumo
    .drop_duplicates("Cenário")
    .sort_values("Cenário")
)

plt.plot(
    actual["Cenário"],
    actual["Mean_Actual_Power"],
    marker="o",
    linewidth=2,
    linestyle="--",
    label="Actual PV Capacity",
)

plt.xlabel("PV Penetration (%)")
plt.ylabel("PV Capacity (kW)")
plt.title("Estimated PV Capacity Across Executions")
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.savefig(
    OUTPUT_DIR / "Estimated_PV_Capacity_All_Executions.png",
    bbox_inches="tight",
)
plt.close()


# ==========================================================
# TEXT REPORT
# ==========================================================

report = OUTPUT_DIR / "Multiple_Executions_Summary.txt"

with open(report, "w", encoding="utf-8") as f:

    f.write("=" * 100 + "\n")
    f.write("MULTIPLE-EXECUTION PV ESTIMATION ANALYSIS\n")
    f.write("=" * 100 + "\n\n")

    f.write(f"Experiment directory:\n{EXPERIMENTOS_DIR}\n\n")
    f.write(
        f"Executions found: {len(pastas_execucao)}/{NUM_EXECUCOES}\n\n"
    )

    f.write("=" * 100 + "\n")
    f.write("OVERALL SUMMARY\n")
    f.write("=" * 100 + "\n\n")

    f.write(overall.to_string(index=False))
    f.write("\n\n")

    f.write("=" * 100 + "\n")
    f.write("STATISTICAL SUMMARY BY CONDITION AND PV PENETRATION\n")
    f.write("=" * 100 + "\n\n")

    f.write(resumo.to_string(index=False))
    f.write("\n\n")

    f.write("=" * 100 + "\n")
    f.write("VOLT-VAR COMPARISON\n")
    f.write("=" * 100 + "\n\n")

    f.write(comparacao_resumo.to_string(index=False))
    f.write("\n\n")

    f.write(
        "Interpretation rule for Error Difference: "
        "With Volt-VAr minus Without Volt-VAr. "
        "Negative values indicate lower estimation error with Volt-VAr.\n"
    )

    f.write("\n\n")
    f.write("=" * 100 + "\n")
    f.write("BEST CLUSTER FREQUENCY\n")
    f.write("=" * 100 + "\n\n")

    f.write(cluster_frequency.to_string(index=False))
    f.write("\n")


# ==========================================================
# CONSOLE
# ==========================================================

print("\n" + "=" * 100)
print("ANALYSIS COMPLETED")
print("=" * 100)

print("\nOVERALL SUMMARY")
print(overall.to_string(index=False))

print("\nSTATISTICAL SUMMARY")
print(resumo.to_string(index=False))

print("\nVOLT-VAR COMPARISON")
print(comparacao_resumo.to_string(index=False))

print("\nResults saved to:")
print(OUTPUT_DIR)

print("\nGenerated files:")
for arquivo in sorted(OUTPUT_DIR.iterdir()):
    print(f"  - {arquivo.name}")
